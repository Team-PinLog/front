/**
 * 홈 "종이에 오려낸 창"의 개방 상태.
 *
 * 모션의 방아쇠는 스크롤도 타이머도 아니고 **사용자 입력**이다. `--open`(0 또는 1) 하나가
 * 종이 네 판·조판·검색 도크·앱 셸을 전부 구동한다. 한 글자라도 치면 창이 통째로 열리고,
 * 다 지우면 그대로 닫힌다.
 *
 * 시안은 `길이 / 6`으로 **개방률**을 만들어 타이핑 속도가 곧 재생 속도가 되게 했는데,
 * 그러면 글자를 지우고 더할 때마다 종이가 조금씩 들썩여 "펼쳐진다"는 인상이 흐려졌다.
 * 지금은 입력 여부만 보고 나머지는 CSS transition(1.05s)이 한 번에 쓸어 연다 —
 * 열리는 속도가 타이핑 속도에 좌우되지 않아 매번 같은 동작이 나온다.
 */

/**
 * 지도가 "가려진 것으로 치고" fitBounds 여유·중심 보정에 반영할 상단 높이(px).
 *
 * 이전 구조(히어로 오버레이)에서는 오버레이가 고정 높이라 그 값을 그대로 넘겼다. 지금은
 * 종이가 열리고 닫히므로 고정값이 아니다 — 다만 지도를 실제로 보는 시점은 **창이 열린
 * 뒤**이고, 그때 위를 가리는 것은 상단으로 올라간 검색 도크뿐이다. 그래서 도크가 차지하는
 * 높이(라벨+입력창+안내문 ≈ 150px)를 기준으로 잡는다. 창이 닫혀 있는 동안은 지도가 아예
 * 안 보이므로 이 값이 무엇이든 화면에 드러나지 않는다.
 */
export const MAP_TOP_OBSTRUCTION_PX = 150;

/**
 * 검색어가 있으면 1(열림), 없으면 0(닫힘).
 *
 * 공백만 친 경우는 닫힌 상태로 둔다 — 스페이스바 한 번에 화면이 열렸다 닫히면 오작동으로 읽힌다.
 */
export function computeOpen(query: string): number {
  return query.trim().length > 0 ? 1 : 0;
}

